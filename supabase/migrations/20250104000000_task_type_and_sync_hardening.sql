-- 1. Add task_type column to public.tasks
ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS task_type text NOT NULL DEFAULT 'manual'
  CHECK (task_type IN ('system_follow_up', 'manual'));

-- 2. Performance Index for task synchronization lookups
CREATE INDEX IF NOT EXISTS idx_tasks_lead_type_completed
  ON public.tasks(lead_id, task_type, completed);

-- 3. Backfill existing follow-up tasks generated by the system
UPDATE public.tasks
SET task_type = 'system_follow_up'
WHERE title LIKE 'Follow up with %' AND task_type = 'manual';

-- 4. Update create_lead_transactional to mark system tasks explicitly
CREATE OR REPLACE FUNCTION public.create_lead_transactional(
  p_workspace_id uuid,
  p_name text,
  p_company text,
  p_email text,
  p_phone text,
  p_service text,
  p_source text,
  p_status text,
  p_deal_value numeric,
  p_next_follow_up timestamptz,
  p_notes text
) RETURNS jsonb AS $$
DECLARE
  v_lead_id uuid;
  v_created_lead jsonb;
  v_user_id uuid := auth.uid();
BEGIN
  IF NOT public.is_workspace_member(p_workspace_id) THEN
    RAISE EXCEPTION 'Access denied: caller is not a member of workspace %', p_workspace_id;
  END IF;

  INSERT INTO public.leads (
    workspace_id, name, company, email, phone,
    service, source, status, deal_value, next_follow_up, notes, assigned_to
  ) VALUES (
    p_workspace_id, trim(p_name), trim(p_company), trim(p_email), nullif(trim(p_phone), ''),
    trim(p_service), trim(p_source), p_status, coalesce(p_deal_value, 0), p_next_follow_up, nullif(trim(p_notes), ''), v_user_id
  ) RETURNING id INTO v_lead_id;

  -- Atomic initial activity record
  INSERT INTO public.activities (
    workspace_id, lead_id, user_id, type, description, metadata
  ) VALUES (
    p_workspace_id,
    v_lead_id,
    v_user_id,
    'note',
    format('Lead created for %s (%s)', trim(p_company), trim(p_service)),
    jsonb_build_object('lead_name', trim(p_name), 'company', trim(p_company), 'action', 'create')
  );

  -- Atomic follow-up task if date scheduled (tagged as system_follow_up)
  IF p_next_follow_up IS NOT NULL THEN
    INSERT INTO public.tasks (
      workspace_id, lead_id, assigned_to, title, due_date, completed, task_type
    ) VALUES (
      p_workspace_id,
      v_lead_id,
      v_user_id,
      format('Follow up with %s on %s', trim(p_name), trim(p_service)),
      p_next_follow_up,
      false,
      'system_follow_up'
    );
  END IF;

  SELECT to_jsonb(l) INTO v_created_lead
  FROM public.leads l
  WHERE l.id = v_lead_id;

  RETURN v_created_lead;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public;

-- 5. Update update_lead_transactional to synchronize ONLY system_follow_up tasks
CREATE OR REPLACE FUNCTION public.update_lead_transactional(
  p_lead_id uuid,
  p_workspace_id uuid,
  p_name text,
  p_company text,
  p_email text,
  p_phone text,
  p_service text,
  p_source text,
  p_status text,
  p_deal_value numeric,
  p_next_follow_up timestamptz,
  p_notes text
) RETURNS jsonb AS $$
DECLARE
  v_old_status text;
  v_old_follow_up timestamptz;
  v_updated_lead jsonb;
  v_user_id uuid := auth.uid();
BEGIN
  IF NOT public.is_workspace_member(p_workspace_id) THEN
    RAISE EXCEPTION 'Access denied: caller is not a member of workspace %', p_workspace_id;
  END IF;

  SELECT status, next_follow_up INTO v_old_status, v_old_follow_up
  FROM public.leads
  WHERE id = p_lead_id AND workspace_id = p_workspace_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Lead not found in workspace %', p_workspace_id;
  END IF;

  UPDATE public.leads
  SET
    name = trim(p_name),
    company = trim(p_company),
    email = trim(p_email),
    phone = nullif(trim(p_phone), ''),
    service = trim(p_service),
    source = trim(p_source),
    status = p_status,
    deal_value = coalesce(p_deal_value, 0),
    next_follow_up = p_next_follow_up,
    notes = nullif(trim(p_notes), ''),
    updated_at = now()
  WHERE id = p_lead_id AND workspace_id = p_workspace_id;

  -- Record status change activity exactly once
  IF v_old_status IS DISTINCT FROM p_status THEN
    INSERT INTO public.activities (
      workspace_id, lead_id, user_id, type, description, metadata
    ) VALUES (
      p_workspace_id,
      p_lead_id,
      v_user_id,
      'status_change',
      format('Status changed from %s to %s', v_old_status, p_status),
      jsonb_build_object('from_status', v_old_status, 'to_status', p_status, 'lead_name', trim(p_name))
    );

    -- Mark ONLY system follow-up tasks as complete when closed won or lost
    -- User-created manual tasks are preserved so pending actions remain intact
    IF p_status IN ('won', 'lost') THEN
      UPDATE public.tasks
      SET completed = true, completed_at = now(), updated_at = now()
      WHERE lead_id = p_lead_id
        AND workspace_id = p_workspace_id
        AND completed = false
        AND task_type = 'system_follow_up';
    END IF;
  END IF;

  -- Synchronize system follow-up task ONLY
  IF v_old_follow_up IS DISTINCT FROM p_next_follow_up THEN
    IF p_next_follow_up IS NULL THEN
      -- Delete only pending system-generated follow-up tasks
      DELETE FROM public.tasks
      WHERE lead_id = p_lead_id
        AND workspace_id = p_workspace_id
        AND completed = false
        AND task_type = 'system_follow_up';
    ELSE
      -- Check if a pending system follow-up task exists to update
      IF EXISTS (
        SELECT 1 FROM public.tasks
        WHERE lead_id = p_lead_id
          AND workspace_id = p_workspace_id
          AND completed = false
          AND task_type = 'system_follow_up'
      ) THEN
        UPDATE public.tasks
        SET due_date = p_next_follow_up,
            title = format('Follow up with %s on %s', trim(p_name), trim(p_service)),
            updated_at = now()
        WHERE lead_id = p_lead_id
          AND workspace_id = p_workspace_id
          AND completed = false
          AND task_type = 'system_follow_up';
      ELSE
        -- No pending system task exists: create a new system_follow_up task
        INSERT INTO public.tasks (
          workspace_id, lead_id, assigned_to, title, due_date, completed, task_type
        ) VALUES (
          p_workspace_id,
          p_lead_id,
          v_user_id,
          format('Follow up with %s on %s', trim(p_name), trim(p_service)),
          p_next_follow_up,
          false,
          'system_follow_up'
        );
      END IF;
    END IF;
  END IF;

  SELECT to_jsonb(l) INTO v_updated_lead
  FROM public.leads l
  WHERE l.id = p_lead_id;

  RETURN v_updated_lead;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public;

-- 6. Enforce least-privilege execute permissions
REVOKE ALL ON FUNCTION public.create_lead_transactional FROM PUBLIC;
REVOKE ALL ON FUNCTION public.update_lead_transactional FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.create_lead_transactional TO authenticated;
GRANT EXECUTE ON FUNCTION public.update_lead_transactional TO authenticated;

